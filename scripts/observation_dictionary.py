def observation_definition(col):
    definitions={
        'model':'Observation-model specification and, for effects, weight-trimming rule.',
        'year':'Prediction time in years after baseline CDR-SB.',
        'estimate':'Standardized difference in modeled CDR-SB change between tau quartiles, normalized per 0.1 SUVR.',
        'tau_q25':'25th percentile of baseline tau SUVR in the target sample.',
        'tau_q75':'75th percentile of baseline tau SUVR in the target sample.',
        'n_standardized_people':'Number of participants used to standardize the outcome contrast.',
        'n_people_with_observed_span_at_least_year':'Participants with observed follow-up spanning at least the prediction time.',
        'units':'Measurement scale and time origin of the effect.',
        'delta_ci_low':'Lower 95% delta-method confidence limit.',
        'delta_ci_high':'Upper 95% delta-method confidence limit.',
        'ci_low':'Lower 95% participant-bootstrap percentile confidence limit.',
        'ci_high':'Upper 95% participant-bootstrap percentile confidence limit.',
        'interval':'Confidence-interval construction.',
        'status':'Numerical estimation or diagnostic status.',
        'reason':'Reason for a diagnostic status.',
        'support_warning':'Whether limited observation-probability support was detected.',
        'original_rule_passed':'Whether the prespecified probability-range diagnostic passed.',
        'original_rule_applicable':'Whether the probability-range diagnostic applies to this estimate.',
        'bootstrap_requested':'Requested participant-bootstrap samples.',
        'bootstrap_attempted':'Attempted participant-bootstrap samples.',
        'bootstrap_valid':'Samples yielding an estimable outcome contrast.',
        'bootstrap_fit_valid':'Samples yielding numerically valid model fits.',
        'section':'Diagnostic component: coverage, fit, probability distribution, weights, balance, or bootstrap.',
        'grouping':'Variable defining a descriptive subgroup.',
        'group':'Subgroup level.',
        'period':'Half-year period index relative to baseline CDR-SB.',
        'people':'Eligible participants in the period or subgroup.',
        'observed_people':'Participants with at least one observed assessment in the window.',
        'visits':'Observed assessments in the window.',
        'median_window_years':'Median duration of eligible windows, in years.',
        'empirical_support':'Window observation pattern: all zero, all one, or variable.',
        'n_variable_windows':'Participant-period windows entering the observation model.',
        'design_rank':'Rank of the observation-model design matrix.',
        'design_columns':'Number of observation-model design columns.',
        'converged':'Whether numerical fitting converged.',
        'separation_warning':'Whether a separation warning was raised.',
        'n_zero_periods':'Number of all-unobserved period strata.',
        'n_one_periods':'Number of all-observed period strata.',
        'p_min':'Minimum fitted observation probability.',
        'p_max':'Maximum fitted observation probability.',
        'positivity_lower':'Lower probability diagnostic threshold (0.001).',
        'positivity_upper':'Upper probability diagnostic threshold (0.999).',
        'n_probability_below':'Windows below the lower fitted-probability threshold.',
        'n_probability_above':'Windows above the upper fitted-probability threshold.',
        'below_observed':'Observed windows below the lower fitted-probability threshold.',
        'below_unobserved':'Unobserved windows below the lower fitted-probability threshold.',
        'above_observed':'Observed windows above the upper fitted-probability threshold.',
        'above_unobserved':'Unobserved windows above the upper fitted-probability threshold.',
        'observed':'Window observation indicator defining a probability-summary subgroup.',
        'n':'Number of records in the reported distribution.',
        'scenario':'Weight-trimming rule.',
        'raw_followup_ess':'Effective follow-up count from untrimmed weights: squared sum divided by sum of squares.',
        'used_followup_ess':'Effective follow-up count from analysis weights.',
        'raw_effective_people':'Effective participant count after aggregating untrimmed weights within participants.',
        'raw_max_person_share':'Largest participant share of total untrimmed weight.',
        'raw_top_five_people_share':'Combined share of total untrimmed weight for the five most-weighted participants.',
        'raw_weight_max':'Maximum untrimmed follow-up weight.',
        'used_weight_max':'Maximum analysis follow-up weight.',
        'trim_low':'Lower weight-trimming cutoff.',
        'trim_high':'Upper weight-trimming cutoff.',
        'clipped_observations':'Assessments whose weights were truncated at a trimming cutoff.',
        'n_followup_visits':'Number of follow-up assessments.',
        'n_people':'Number of distinct participants.',
        'n_observations':'Number of baseline and follow-up assessments.',
        'variable':'Covariate assessed for balance.',
        'target_mean':'Mean covariate value across eligible target windows.',
        'observed_mean':'Unweighted mean covariate value across observed windows.',
        'weighted_mean':'Weighted mean covariate value across observed windows.',
        'unweighted_smd':'Observed-minus-target mean divided by target SD, before weighting.',
        'weighted_smd':'Weighted-minus-target mean divided by target SD.',
        'target_sd':'Covariate SD in eligible target windows.',
        'target_range':'Covariate range in eligible target windows.',
        'numerical_tolerance':'Tolerance used to identify constant or numerically degenerate covariates.',
        'smd_status':'Whether a standardized mean difference is numerically defined.',
        'smd_applicable':'Whether standardized balance is applicable to this covariate.',
        'target_windows':'Eligible participant-period windows.',
        'observed_windows':'Participant-period windows with observed assessments.',
        'scope':'Population or diagnostic scope.',
    }
    if col in definitions: return definitions[col]
    if col.startswith('bootstrap_original_rule_'):
        suffix=col.removeprefix('bootstrap_original_rule_')
        return 'Number of bootstrap samples with probability-range diagnostic status: '+suffix.replace('_',' ')+'.'
    used=col.startswith('used_'); key=col.removeprefix('used_')
    labels={'minimum':'minimum','maximum':'maximum','median':'median','q01':'1st percentile','q05':'5th percentile','q25':'25th percentile','q75':'75th percentile','q95':'95th percentile','q99':'99th percentile','n':'record count'}
    if key in labels:
        return ('Analysis-weight ' if used else 'Distribution ')+labels[key]+'. The diagnostic section identifies the summarized quantity.'
    raise KeyError('Missing observation definition: '+col)

